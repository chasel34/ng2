package com.chasel.ng2n.ui.perf

/**
 * **真机上才量得出来的那几刀**的开关(票 59 二轮)。
 *
 * 这里的常量都不是可配置项,而是**编译期口子**:改一个字面量、重打一包、按票 59 的
 * 对拍口径再采一次 15 秒富 trace,就能把「这一刀值几毫秒」钉死。默认值一律等于
 * **当前发布行为**,所以正常构建下这个文件等于不存在。
 *
 * 为什么不做成运行期设置:这两条都会改 window / 层结构,运行期切换本身就会引入
 * 一次重画与一次 GPU 尖峰,反而污染要量的那条曲线;而且它们都不是给用户的选项。
 *
 * `PerfFlagsTest` 钉住默认值,防止哪次实验完忘了改回来。
 */
object PerfFlags {

  /**
   * 首帧之后把 `android:windowBackground` 置空(默认 **false** = 保持现状)。
   *
   * `DecorView` 的窗口底色是**每帧一次满屏不透明填充**(1220×2712 = 3.31Mpx),而
   * Compose 侧首页自己就铺满了 `colors.bg`,理论上这一层从第一帧之后就纯属浪费。
   *
   * 不敢默认开的理由:等价性取决于「Compose 侧**任何一帧**都铺满不透明底色」。
   * `NavDisplay` 转场中途、Activity 重建、系统缩略图截取这些时刻有没有空档,
   * 静态代码看不出来;HWUI 又是「谁都不画就留着上一帧的残留」,赌错的表现是黑闪或
   * 残影,只有真机能验。
   *
   * **真机验法**(票 59 二轮写给 codex 的那条):
   * 1. 把这个常量改成 `true`,`./gradlew :app:assembleRelease` 重打;
   * 2. 冷启动 → 首页 → 抽屉开合 → 进设置 → 返回 → 切 tab → 切后台再回来 →
   *    切系统深色模式,全程录屏,逐帧看有没有黑闪 / 残影 / 半屏旧内容;
   * 3. 没有的话再采一次 15 秒富 trace,对拍 GPU fence 分布(整体 p50/p95/max)。
   * 出现任何一次闪就把它改回 `false` 并在票里记下现象,别留半开状态。
   */
  const val BLANK_WINDOW_BACKGROUND_AFTER_FIRST_FRAME = false

  /**
   * 抽屉面板带不带 `.shadow(Elevation.level2)`(默认 **true** = 保持现状)。
   *
   * **这不是可发布档位**——关掉是有视觉差的(面板右缘那条投影没了)。它只是把
   * 「elevation 阴影在 900×2712 的面板上每帧要几毫秒」变成一次可做的对照实验:
   * 同一份脚本各采一次富 trace,GPU fence 中位数之差就是阴影的钱。
   *
   * 静态归因见 `DrawerHost` 面板那一段注释:按 HWUI/Skia 对**不透明遮挡物**的处理,
   * 阴影应该只画外圈模糊环、且三条环在窗口外被裁掉,不该是大头。这个口子是用来
   * 证伪它的。
   */
  const val DRAWER_PANEL_SHADOW = true
}
